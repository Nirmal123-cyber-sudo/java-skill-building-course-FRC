
public class DefinedMethods1_PracticeExercise2 {

    static void printHeader() {
        System.out.println("==============================");
        System.out.println("        MY WEBPAGE");
        System.out.println("==============================");
    }

    static void printBody() {
        System.out.println("Welcome to my webpage!");
        System.out.println("This is the main content.");
    }

    static void printFooter() {
        System.out.println("==============================");
        System.out.println("       Thank You!");
        System.out.println("==============================");
    }

    public static void main(String[] args) {

        printHeader();
        printBody();
        printFooter();

    }
}
